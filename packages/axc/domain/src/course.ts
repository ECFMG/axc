export const COURSE_MODALITIES = ['online', 'in-person', 'hybrid'] as const;
export const COURSE_STATUSES = ['draft', 'active', 'retired'] as const;

type CourseModality = (typeof COURSE_MODALITIES)[number];
type CourseStatus = (typeof COURSE_STATUSES)[number];

/** Training course offered in the catalog. */
export interface Course {
	id: string;
	title: string;
	summary: string;
	modality: CourseModality;
	status: CourseStatus;
	tags: readonly string[];
	createdAt: string;
	updatedAt: string;
}

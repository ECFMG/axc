import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { listFiles } from './support/source-files.ts';

// Docusaurus only reports a dangling sidebar id when the site is actually
// rebuilt, and a cached build hides it. This check reproduces the id rules
// (path relative to docs/, extension dropped, numeric "NNNN-" prefixes removed
// from every segment, frontmatter `id` wins) so a broken sidebar fails here.
const packageDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsApp = path.resolve(packageDir, '../../../apps/docs');
const docsDir = path.join(docsApp, 'docs');
const sidebarsFile = path.join(docsApp, 'sidebars.ts');

const NON_ID_KEYS = new Set(['type', 'label', 'href', 'dirName', 'className', 'description', 'title', 'collapsible', 'collapsed']);
const NON_ID_VALUES = new Set(['doc', 'category', 'link', 'autogenerated', 'ref', 'html', 'generated-index']);

export function docIdFor(relativePath: string, content: string): string {
	const explicit = /^---\n[\s\S]*?^id:\s*['"]?([^'"\n]+)['"]?\s*$[\s\S]*?^---/m.exec(content);
	const withoutExtension = relativePath.replace(/\.mdx?$/, '');
	const segments = withoutExtension.split('/').map((segment) => segment.replace(/^\d+-/, ''));
	if (explicit) {
		segments[segments.length - 1] = explicit[1]?.trim() ?? '';
	}
	return segments.join('/');
}

export function sidebarDocIds(source: string): string[] {
	const ids: string[] = [];
	for (const match of source.matchAll(/(?:(\w+)\s*:\s*)?['"]([^'"\n]+)['"]/g)) {
		const key = match[1];
		const value = match[2] ?? '';
		if (key && NON_ID_KEYS.has(key)) {
			continue;
		}
		if (NON_ID_VALUES.has(value) || !/^[\w./-]+$/.test(value) || value.startsWith('@')) {
			continue;
		}
		ids.push(value);
	}
	return ids;
}

describe('docs sidebar', () => {
	it('every sidebar id resolves to a document and every document is listed', async () => {
		const sidebar = await readFile(sidebarsFile, 'utf8');
		const docs = await listFiles(docsDir, (filePath) => /\.mdx?$/.test(filePath));
		const existing = new Map(docs.map((doc) => [docIdFor(doc.relativePath, doc.content), doc.relativePath]));
		const listed = new Set(sidebarDocIds(sidebar));

		const dangling = [...listed].filter((id) => !existing.has(id)).map((id) => `sidebars.ts lists "${id}" but no document has that id (numeric prefixes are dropped from ids)`);
		const unlisted = [...existing.entries()].filter(([id]) => !listed.has(id)).map(([id, file]) => `apps/docs/docs/${file} (id "${id}") is not reachable from sidebars.ts`);

		expect([...dangling, ...unlisted]).toEqual([]);
	});
});
